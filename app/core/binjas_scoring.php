// ============================================================
// CORE: Lookup skor dari tabel
// Port dari score(val, table) di kalkulator.js
// ============================================================
function binjas_score(float $val, array $table): int
{
    if ($val <= 0) return 0;

    // Cek apakah tabel berbasis waktu (flag true di akhir)
    $is_time = (end($table) === true);

    foreach ($table as $entry) {
        if (!is_array($entry)) continue; // skip flag true
        [$threshold, $skor] = $entry;
        if ($is_time ? $val <= $threshold : $val >= $threshold) {
            return (int)$skor;
        }
    }

    return 1; // di bawah minimum → tetap dapat 1 (sesuai kalkulator.js)
}

// ============================================================
// PREDIKAT: Port dari rating(s)
// ============================================================
function binjas_predikat(float $skor): string
{
    if ($skor >= 81) return 'Baik Sekali';
    if ($skor >= 71) return 'Baik';
    if ($skor >= 61) return 'Cukup';
    if ($skor >= 41) return 'Kurang';
    return 'Kurang Sekali';
}

// ============================================================
// MAIN: Hitung semua skor binjas
// ============================================================
function binjas_hitung(
    string  $institusi,        // 'polri' | 'tni'
    string  $gender,           // 'pria' | 'wanita'
    float   $lari,             // meter
    float   $pullup,           // repetisi (pullup/chinning)
    float   $situp,            // repetisi
    float   $pushup,           // repetisi
    float   $shuttle,          // detik
    ?float  $lunges     = null, // repetisi, opsional
    ?float  $renang     = null, // detik, opsional
    string  $renang_gaya = 'dada' // 'dada' | 'bebas' (hanya TNI)
): array {
    $inst = strtolower($institusi);
    $gen  = strtolower($gender);

    if (!in_array($inst, ['polri', 'tni'], true)) $inst = 'polri';
    if (!in_array($gen,  ['pria', 'wanita'], true)) $gen = 'pria';

    $ST      = _binjas_tables();
    $tb      = $ST[$inst][$gen];

    // Kunci pullup/chinning: wanita pakai 'chinning', pria 'pullup'
    $pu_key  = ($gen === 'wanita') ? 'chinning' : 'pullup';

    $n_lari    = binjas_score($lari,    $tb['lari']);
    $n_pullup  = binjas_score($pullup,  $tb[$pu_key]);
    $n_situp   = binjas_score($situp,   $tb['situp']);
    $n_pushup  = binjas_score($pushup,  $tb['pushup']);
    $n_shuttle = binjas_score($shuttle, $tb['shuttle']);

    // B-items: pullup, situp, pushup, shuttle [+ lunges jika ada]
    $b_items = [$n_pullup, $n_situp, $n_pushup, $n_shuttle];
    $n_lunges = null;

    if ($lunges !== null && $lunges > 0 && isset($tb['lunges'])) {
        $n_lunges = binjas_score($lunges, $tb['lunges']);
        if ($n_lunges > 0) $b_items[] = $n_lunges;
    }

    // Cek ada skor nol (TMS = Tidak Memenuhi Syarat)
    $has_zero = ($n_lari === 0 || in_array(0, [$n_pullup, $n_situp, $n_pushup, $n_shuttle], true));

    // Rata-rata B items
    $avg_b   = array_sum($b_items) / count($b_items);
    $nilai_ab = ($n_lari + $avg_b) / 2;

    // Renang (opsional)
    $n_renang       = null;
    $nilai_gabungan = null;
    $renang_tms     = false;

    if ($renang !== null && $renang > 0) {
        if ($inst === 'tni') {
            $renang_gaya = in_array($renang_gaya, ['dada', 'bebas'], true) ? $renang_gaya : 'dada';
            $renang_tbl  = $tb['renang'][$renang_gaya] ?? $tb['renang']['dada'];
        } else {
            $renang_tbl = $tb['renang'];
        }
        $n_renang   = binjas_score($renang, $renang_tbl);
        if ($n_renang === 0) $renang_tms = true;
        $nilai_gabungan = $nilai_ab * 0.8 + $n_renang * 0.2;
    }

    // Passing grade: Polri=61, TNI=41
    $passing_grade = ($inst === 'polri') ? 61 : 41;
    $is_lulus      = ($nilai_ab >= $passing_grade && !$has_zero && !$renang_tms);

    $total_skor = (int)round($nilai_ab);
    $predikat   = binjas_predikat($nilai_ab);

    return [
        'skor_lari'      => $n_lari,
        'skor_pullup'    => $n_pullup,
        'skor_situp'     => $n_situp,
        'skor_pushup'    => $n_pushup,
        'skor_shuttle'   => $n_shuttle,
        'skor_lunges'    => $n_lunges,
        'skor_renang'    => $n_renang,
        'nilai_ab'       => round($nilai_ab, 2),
        'nilai_gabungan' => $nilai_gabungan !== null ? round($nilai_gabungan, 2) : null,
        'total_skor'     => $total_skor,
        'predikat'       => $predikat,
        'lulus'          => $is_lulus,
        'passing_grade'  => $passing_grade,
        'has_zero'       => $has_zero,
        'renang_tms'     => $renang_tms,
    ];
}

